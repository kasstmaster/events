// Development-only catalog generation. Does not change application source or data.
import { readFile, writeFile } from "node:fs/promises";
import { parsers } from "prettier/plugins/babel";
import {
  designControls,
  roleDefaults,
  layoutLabels,
  viewLabels,
} from "../public/ui-system.js";
import { cardFieldLabels } from "../public/card-system.js";
const catalog = new Set([
  ...Object.values(layoutLabels),
  ...Object.values(viewLabels),
  ...Object.values(cardFieldLabels),
]);
const add = (value) => {
  if (typeof value === "string") {
    const key = value.trim();
    if (
      key.length > 1 &&
      key.length <= 1000 &&
      /[a-z]/i.test(key) &&
      !/[{}=<>]/.test(key) &&
      !["GET", "POST", "PUT", "DELETE", "PATCH", "UTC"].includes(key)
    )
      catalog.add(key);
  }
};
designControls(roleDefaults, {
  field: (label) => {
    add(label);
    return "";
  },
  select: (label) => {
    add(label);
    return "";
  },
});
function walk(node, parent, fn) {
  if (!node || typeof node !== "object") return;
  if (node.type) fn(node, parent);
  for (const [key, value] of Object.entries(node)) {
    if (["loc", "tokens", "comments", "extra"].includes(key)) continue;
    if (Array.isArray(value)) value.forEach((item) => walk(item, node, fn));
    else if (value && typeof value === "object") walk(value, node, fn);
  }
}
for (const file of [
  "public/app.js",
  "public/editor-tools.js",
  "public/family-ui.js",
  "server/family-api.js",
  "server/family-permissions.js",
  "server/family-tasks.js",
  "server/guest-identities.js",
  "server/recipe-import.js",
  "server/handler.js",
  "server/model.js",
  "server/features.js",
  "server/feature-api.js",
  "server/reminders.js",
  "server/account-deletion.js",
]) {
  const source = await readFile(file, "utf8");
  walk(parsers.babel.parse(source, {}), null, (node, parent) => {
    if (node.type === "TemplateElement" || node.type === "StringLiteral") {
      const raw =
        node.type === "TemplateElement" ? node.value.cooked : node.value;
      if (typeof raw !== "string") return;
      if (raw.includes("<")) {
        for (const match of raw.matchAll(/(?:^|>)([^<>]+)(?=<|$)/g))
          add(match[1]);
        for (const match of raw.matchAll(
          /(?:aria-label|placeholder|title)="([^"]*)"/g,
        ))
          add(match[1]);
      }
      if (parent?.type === "CallExpression") {
        const name = parent.callee?.name,
          index = parent.arguments.indexOf(node);
        if (["C", "H", "notify", "Error"].includes(name) && index === 0)
          add(raw);
        if (["field", "select", "area", "modal"].includes(name) && index === 0)
          add(raw);
        if (["button", "action"].includes(name) && index === 1) add(raw);
        if (name === "fail" && index === 1) add(raw);
      }
      if (parent?.type === "ConditionalExpression" && /^[A-Z]|\s/.test(raw))
        add(raw);
      if (
        parent?.type === "ArrayExpression" &&
        parent.elements[1] === node &&
        /^[A-Z]/.test(raw)
      )
        add(raw);
    }
  });
}
for (const key of [
  "Save",
  "Cancel",
  "Home",
  "Print",
  "RSVPs",
  "Sign out",
  "When",
  "Where",
  "RSVP By",
  "Attending",
  "Invited",
  "Event appearance",
  "Some text may be clipped. Increase the field height or reduce its size before exporting.",
])
  add(key);
await writeFile(
  "public/ui-copy.js",
  "// Generated by npm run copy:catalog. Shared wording stays separate from content and styles.\nexport const copyCatalog=" +
    JSON.stringify([...catalog].sort(), null, 2) +
    ";\n",
);
