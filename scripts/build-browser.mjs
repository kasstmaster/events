// Deterministic generated public entry points. No runtime/provider requests.
import { build, transform } from "esbuild";
import { bindBrowseMenus } from "../public/browse-ui.js";
import {
  requestRecipientAccess,
  startEarlyInteractions,
} from "../public/early-interactions.js";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, ".."),
  check = process.argv.includes("--check");
for (const entry of ["auth-bootstrap", "app"]) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [`client/${entry}.js`],
    bundle: true,
    write: false,
    metafile: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minifyWhitespace: true,
    minifySyntax: true,
    minifyIdentifiers: false,
    legalComments: "none",
    plugins: [
      {
        name: "public-modules",
        setup(b) {
          b.onResolve({ filter: /^https:\/\// }, (a) => ({
            path: a.path,
            external: true,
          }));
          if (entry === "auth-bootstrap")
            b.onResolve({ filter: /^\/app\.js$/ }, () => ({
              path: "/app.js",
              external: true,
            }));
          if (entry === "app")
            b.onResolve({ filter: /(?:^|\/)auth-bootstrap\.js$/ }, () => ({
              path: "/auth-bootstrap.js",
              external: true,
            }));
          if (entry === "app")
            b.onResolve(
              { filter: /^\/(?:editor-tools|appearance-editor)\.js$/ },
              (a) => ({ path: a.path, external: true }),
            );
          b.onResolve({ filter: /^\/.*\.js$/ }, (a) => ({
            path: resolve(root, "public" + a.path),
          }));
        },
      },
    ],
  });
  const output =
    "// Generated by scripts/build-browser.mjs; edit client/ and public source modules.\n" +
    result.outputFiles[0].text;
  const imports = Object.values(result.metafile.outputs).flatMap(
    (output) => output.imports,
  );
  if (
    entry === "auth-bootstrap" &&
    (Buffer.byteLength(output) > 12000 ||
      imports.some((i) => i.kind !== "dynamic-import" || i.path !== "/app.js"))
  )
    throw Error(
      "Transfer bootstrap must stay small and independent from the full app.",
    );
  if (
    entry === "app" &&
    imports.some(
      (i) => i.kind === "import-statement" && i.path !== "/auth-bootstrap.js",
    )
  )
    throw Error(
      "The app must not reintroduce a static module request waterfall.",
    );
  const path = resolve(root, `public/${entry}.js`);
  if (check) {
    if ((await readFile(path, "utf8")) !== output)
      throw Error(`Stale browser build: run npm run build:browser (${entry}).`);
  } else await writeFile(path, output);
}
// Compile the inline entry at build time so Worker bundling cannot insert
// references to server-only helpers into the executable browser source.
const { code: earlyScript } = await transform(
  `(${startEarlyInteractions.toString()})(${bindBrowseMenus.toString()},${requestRecipientAccess.toString()});`,
  { target: "es2022", minify: true },
);
if (Buffer.byteLength(earlyScript) > 10000 || /<\/script/i.test(earlyScript))
  throw Error("Early interaction entry must be small and safe to inline.");
const earlyOutput =
  "// Generated by scripts/build-browser.mjs.\n// prettier-ignore\nexport const earlyInteractionScript = " +
  JSON.stringify(earlyScript.trim()) +
  ";\n";
const earlyPath = resolve(root, "server/early-interaction-script.js");
if (check) {
  if ((await readFile(earlyPath, "utf8")) !== earlyOutput)
    throw Error("Stale early interaction entry: run npm run build:browser.");
} else await writeFile(earlyPath, earlyOutput);

console.log(
  check
    ? "Browser entries match their reviewed sources."
    : "Browser entries built from shared sources.",
);
